"""Turn a Genie agent definition (.geniespace.json) into the bundle resource.

Bundles resolve ${var.catalog} / ${var.schema} only when the definition is inline
in the resource YAML, not inside a separate file_path JSON (tested 2026-11-06,
CLI 1.21.0). So the .geniespace.json is the working copy, and this script writes
it inline into resources/<key>.genie.yml with environment names swapped for
bundle variables.

Usage:
  python3 scripts/sync_agent.py src/taxi_agent.geniespace.json \
      --key taxi_agent --from-catalog <dev catalog> --from-schema <dev schema>

--from-catalog/--from-schema: literal names to replace (as exported from dev).
"""
import argparse
import json
import pathlib
import re

p = argparse.ArgumentParser()
p.add_argument("space_json")
p.add_argument("--key", default="taxi_agent")
p.add_argument("--title", default="Taxi Trips")
p.add_argument("--description", default=(
    "Answers questions about NYC taxi trips, fares and revenue. "
    "Built on the trip_metrics metric view."))
p.add_argument("--from-catalog")
p.add_argument("--from-schema")
a = p.parse_args()

text = pathlib.Path(a.space_json).read_text()
if a.from_catalog and a.from_schema:
    pat = re.compile(rf"`?{re.escape(a.from_catalog)}`?\.`?{re.escape(a.from_schema)}`?\.")
    text = pat.sub("${var.catalog}.${var.schema}.", text)
space = json.loads(text)


def canonical(o):
    """Stable order: Genie export order differs from authoring order, so sort
    id-keyed arrays by id, data sources by identifier, columns by name."""
    if isinstance(o, dict):
        return {k: canonical(v) for k, v in o.items()}
    if isinstance(o, list):
        o = [canonical(x) for x in o]
        for key in ("id", "identifier", "column_name"):
            if o and all(isinstance(x, dict) and key in x for x in o):
                return sorted(o, key=lambda x: x[key])
        return o
    return o


# Genie stores metric views under data_sources.tables; match that so pulls diff cleanly.
ds = space.get("data_sources", {})
if "metric_views" in ds:
    ds["tables"] = ds.get("tables", []) + ds.pop("metric_views")
space = canonical(space)

leftover = [m for m in re.findall(r"\b\w+\.\w+\.\w+\b", json.dumps(space)) if "var." not in m]
if a.from_catalog and any(m.startswith(a.from_catalog + ".") for m in leftover):
    raise SystemExit(f"hardcoded catalog still present: {leftover[:5]}")

root = pathlib.Path(__file__).resolve().parent.parent
# Write the parameterized, canonical form back to the working copy too, so it never
# keeps dev names after a pull.
src_path = pathlib.Path(a.space_json).resolve()
src_path.write_text(json.dumps(space, indent=2, sort_keys=True) + "\n")
rel = src_path.relative_to(root) if src_path.is_relative_to(root) else src_path
out = root / "resources" / f"{a.key}.genie.yml"
body = json.dumps(space, indent=2, sort_keys=True)  # JSON is valid YAML; sorted keys keep diffs clean
body = "\n".join("      " + line for line in body.splitlines()).lstrip()
out.write_text(f"""# Generated by scripts/sync_agent.py from {rel}. Edit the agent in the
# dev UI, pull it with `make pull`, then commit this file.
resources:
  genie_spaces:
    {a.key}:
      title: {a.title}
      description: {a.description}
      warehouse_id: ${{resources.sql_warehouses.genie_wh.id}}
      permissions:
        - level: CAN_RUN
          group_name: ${{var.consumer_group}}
      serialized_space: {body}
""")
print(f"wrote {out}")
